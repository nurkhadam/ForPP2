# 1. Grading system
score = 85
if score >= 90: print("Grade: A")
elif score >= 80: print("Grade: B")
else: print("Grade: C")

# 2. Positive/Negative/Zero
x = 0
if x > 0: print("Positive")
elif x < 0: print("Negative")
else: print("Zero")

# 3. Categorizing colors
color = "red"
if color == "blue": print("Sky")
elif color == "green": print("Grass")
else: print("Unknown")

# 4. Age groups
age = 15
if age < 13: print("Child")
elif age < 20: print("Teen")
else: print("Adult")

# 5. Temperature check
temp = 25
if temp > 30: print("Hot")
elif temp > 20: print("Warm")
else: print("Cold")