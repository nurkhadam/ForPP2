# 1. One line if
if 5 > 2: print("Five > Two")

# 2. Ternary operator (If Else)
print("A") if 10 > 20 else print("B")

# 3. Short hand assignment
status = "OK" if 200 == 200 else "Error"

# 4. Nested ternary
a = 10; b = 10
print("=") if a == b else print(">") if a > b else print("<")

# 5. Conditional print
print("Success") if True else None